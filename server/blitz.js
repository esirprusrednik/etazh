const GRACE_MS = 3000;       // сеть и анимация — не повод проиграть
const MAX_BEANS = 10;        // по зерну за верный ответ, не больше 10 за набор
const LEADERS = 10;

function shuffle(arr, rnd = Math.random) {
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i--) { const j = Math.floor(rnd() * (i + 1)); [a[i], a[j]] = [a[j], a[i]]; }
  return a;
}

// День промежуточного итога: последняя пятница внутри набора, а если пятниц в нём нет — последний день
function summaryDay(set) {
  for (let t = Date.parse(set.to + 'T12:00:00Z'); t >= Date.parse(set.from + 'T12:00:00Z'); t -= 864e5) if (new Date(t).getUTCDay() === 5) return new Date(t).toISOString().slice(0, 10);
  return set.to;
}
const ddmm = (d) => d.slice(8) + '.' + d.slice(5, 7);
// Текст пуша-итога. board — { top, place, players }; сыгравшему — место, остальным — сколько осталось и кто впереди
function summaryText(set, board, day) {
  const last = set.to === day ? 'Сегодня последний день' : `Закрывается ${ddmm(set.to)}`;
  const lead = board.top[0];
  if (board.place) return board.place === 1 ? `Ты ${board.players > 1 ? `первый из ${board.players}` : 'пока один в таблице'}. ${last} — позови своих, пусть попробуют догнать.`
    : `Ты ${board.place}-й из ${board.players}, впереди — ${lead.nick}. ${last}.`;
  return lead ? `${last}. Сыграли уже ${board.players}, лидер — ${lead.nick}. Пара минут — и ты в таблице.` : `${last}. Пока никто не сыграл — первое место свободно.`;
}

function register(ctx) {
  const { db, q, route, requireUser, bad, U, addBeans, onEvent, notify, fireAndForget } = ctx;

  db.exec(`
  CREATE TABLE IF NOT EXISTS blitz_runs (
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    set_id TEXT NOT NULL,
    started_at INTEGER NOT NULL, finished_at INTEGER,
    plan TEXT NOT NULL,          -- [{q, perm:[индексы вариантов в показанном порядке]}]
    pos INTEGER NOT NULL DEFAULT 0, score INTEGER NOT NULL DEFAULT 0, beans INTEGER NOT NULL DEFAULT 0,
    PRIMARY KEY (user_id, set_id)
  );
  `);

  const activeSet = () => {
    const d = U.msk().day;
    return SETS.filter((s) => s.from <= d && d <= s.to).sort((a, b) => (a.from < b.from ? 1 : -1))[0] || null;
  };
  // Тренировка — повторное прохождение без рейтинга и зёрен. Живёт в той же таблице под ключом «набор:p»,
  // поэтому в лидеры, прошлые блицы и сводку не попадает; каждая новая тренировка заменяет прежнюю
  // Тренироваться можно на текущем наборе (после зачётной попытки) и на любом прошедшем — его вопросы уже не тайна
  const pracSet = (id) => { const d = U.msk().day; return (id && SETS.find((x) => x.id === String(id) && x.to < d)) || activeSet(); };
  const keyOf = (set, prac) => (prac ? set.id + ':p' : set.id);
  const runOf = (uid, set, prac) => q('SELECT * FROM blitz_runs WHERE user_id = ? AND set_id = ?').get(uid, keyOf(set, prac));
  const deadline = (run, set) => run.started_at + set.secs * 1000;

  function finish(run, set, prac) {
    if (run.finished_at) return run;
    const at = Math.min(U.now(), deadline(run, set));
    const beans = prac ? 0 : addBeans(run.user_id, 'blitz', Math.min(run.score, MAX_BEANS) || 0) || 0;
    q('UPDATE blitz_runs SET finished_at = ?, beans = ? WHERE user_id = ? AND set_id = ?').run(at, beans, run.user_id, keyOf(set, prac));
    if (!prac && onEvent) onEvent('blitz', run.user_id, { score: run.score });
    return runOf(run.user_id, set, prac);
  }

  function questionView(run, set) {
    const plan = JSON.parse(run.plan);
    const item = plan[run.pos];
    if (!item) return null;
    const [text, opts] = set.questions[item.q];
    return { n: run.pos + 1, total: plan.length, text, options: item.perm.map((i) => opts[i]) };
  }

  function leaderboard(set, uid) {
    const rows = q(`SELECT r.user_id, r.score, r.finished_at - r.started_at AS ms, u.nick FROM blitz_runs r JOIN users u ON u.id = r.user_id
      WHERE r.set_id = ? AND r.finished_at IS NOT NULL AND u.nick IS NOT NULL ORDER BY r.score DESC, ms ASC`).all(set.id);
    const place = rows.findIndex((r) => r.user_id === uid);
    return { top: rows.slice(0, LEADERS).map((r, i) => ({ place: i + 1, nick: r.nick, score: r.score, secs: Math.round(r.ms / 1000), me: r.user_id === uid })), place: place >= 0 ? place + 1 : null, players: rows.length };
  }

  // Прошедшие наборы, в которых кто-то дошёл до конца: свежие сверху
  const pastSets = () => {
    const d = U.msk().day;
    const played = new Set(q('SELECT DISTINCT set_id AS id FROM blitz_runs WHERE finished_at IS NOT NULL').all().map((r) => r.id));
    return SETS.filter((s) => s.to < d && played.has(s.id)).sort((a, b) => (a.to < b.to ? 1 : -1));
  };
  function past(uid) {
    return pastSets().map((set) => {
      const run = runOf(uid, set);
      return {
        id: set.id, title: set.title, from: set.from, to: set.to, count: set.questions.length, board: leaderboard(set, uid),
        my: run && run.finished_at ? { score: run.score, answered: run.pos, secs: Math.round((run.finished_at - run.started_at) / 1000) } : null
      };
    });
  }

  function view(uid, prac, setId) { return { ...viewNow(uid, prac, setId), past: pastSets().length }; }
  function viewNow(uid, prac, setId) {
    const set = prac ? pracSet(setId) : activeSet();
    if (!set) return { set: null };
    let run = runOf(uid, set, prac);
    if (run && !run.finished_at && U.now() > deadline(run, set) + GRACE_MS) run = finish(run, set, prac);
    const base = { ...(prac ? { practice: true, archive: set !== activeSet() } : {}), set: { id: set.id, title: set.title, emoji: set.emoji, desc: set.desc, secs: set.secs, count: set.questions.length, to: set.to, maxBeans: MAX_BEANS } };
    if (!run) return { ...base, state: 'new', board: leaderboard(set, uid) };
    if (!run.finished_at) return { ...base, state: 'play', leftMs: Math.max(0, deadline(run, set) - U.now()), score: run.score, question: questionView(run, set) };
    return { ...base, state: 'done', score: run.score, answered: run.pos, beans: run.beans, secs: Math.round((run.finished_at - run.started_at) / 1000), board: leaderboard(set, uid) };
  }
  const isPrac = (v) => v === true || v === 1 || v === '1' || v === 'true';

  route('GET', '/api/blitz', async (req, body, query) => view(requireUser(req).id, isPrac(query && query.practice), query && query.set));
  // Ошибки в браузере: без них поломку на чужом телефоне не найти. Пишем только текст ошибки, место в коде,
  // семейство устройства и версию приложения — без пользователя, без адреса. Храним последние 300
  db.exec('CREATE TABLE IF NOT EXISTS client_errors (id INTEGER PRIMARY KEY, at INTEGER NOT NULL, msg TEXT NOT NULL, place TEXT, device TEXT, build TEXT, screen TEXT)');
  const deviceOf = (ua) => { ua = String(ua || ''); const os = /iPhone|iPad|iPod/.test(ua) ? 'iOS ' + ((ua.match(/OS (\d+)[_.](\d+)/) || []).slice(1).join('.') || '?') : /Android/.test(ua) ? 'Android ' + ((ua.match(/Android (\d+)/) || [])[1] || '?') : /Mac OS X/.test(ua) ? 'macOS' : /Windows/.test(ua) ? 'Windows' : 'другое';
    return os + ' · ' + (/YaBrowser/.test(ua) ? 'Яндекс' : /CriOS|Chrome\//.test(ua) ? 'Chrome' : /FxiOS|Firefox\//.test(ua) ? 'Firefox' : /Safari\//.test(ua) ? 'Safari' : 'другой'); };
  let errBudget = { at: 0, n: 0 };
  route('POST', '/api/client-error', async (req, body) => {
    requireUser(req);
    const now = Date.now();
    if (now - errBudget.at > 60e3) errBudget = { at: now, n: 0 };
    if (++errBudget.n > 30) return { ok: true }; // не больше 30 записей в минуту со всех
    const cut = (v, n) => String(v || '').replace(/[\w.+-]+@[\w.-]+/g, '<почта>').slice(0, n);
    q('INSERT INTO client_errors (at, msg, place, device, build, screen) VALUES (?, ?, ?, ?, ?, ?)').run(now, cut(body && body.msg, 300), cut(body && body.place, 200), deviceOf(req.headers['user-agent']), cut(body && body.build, 40), cut(body && body.screen, 40));
    q('DELETE FROM client_errors WHERE id <= (SELECT MAX(id) FROM client_errors) - 300').run();
    return { ok: true };
  });
  // «Пульс»: пока открыто окно (блиц, форма), клиент ничего не запрашивает, и простаивающее соединение на мобильной сети
  // или за VPN может молча умереть — следующий запрос тогда висит. Крошечный запрос раз в несколько секунд держит его живым
  route('GET', '/api/ping', async () => ({ ok: 1 }));
  route('GET', '/api/blitz/past', async (req) => ({ sets: past(requireUser(req).id) }));

  route('POST', '/api/blitz/start', async (req, body) => {
    const u = requireUser(req);
    const prac0 = isPrac(body && body.practice);
    const set = prac0 ? pracSet(body && body.set) : activeSet();
    if (!set) throw bad('Сейчас блица нет — загляни позже.');
    if (prac0) {
      // Текущий набор — только после зачётной попытки, иначе тренировкой можно подсмотреть вопросы. Прошедший — всем
      const rated = runOf(u.id, set);
      if (set === activeSet() && (!rated || !rated.finished_at)) throw bad('Сначала пройди блиц на результат.');
      const plan = shuffle(set.questions.map((_, i) => i)).map((qi) => ({ q: qi, perm: shuffle(set.questions[qi][1].map((_, i) => i)) }));
      q('DELETE FROM blitz_runs WHERE user_id = ? AND set_id = ?').run(u.id, keyOf(set, true));
      q('INSERT INTO blitz_runs (user_id, set_id, started_at, plan) VALUES (?, ?, ?, ?)').run(u.id, keyOf(set, true), U.now(), JSON.stringify(plan));
      return view(u.id, true, set.id);
    }
    if (!runOf(u.id, set)) {
      const plan = shuffle(set.questions.map((_, i) => i)).map((qi) => ({ q: qi, perm: shuffle(set.questions[qi][1].map((_, i) => i)) }));
      q('INSERT OR IGNORE INTO blitz_runs (user_id, set_id, started_at, plan) VALUES (?, ?, ?, ?)').run(u.id, set.id, U.now(), JSON.stringify(plan));
    }
    return view(u.id);
  });

  route('POST', '/api/blitz/answer', async (req, body) => {
    const u = requireUser(req);
    const prac = isPrac(body && body.practice);
    const set = prac ? pracSet(body && body.set) : activeSet();
    if (!set) throw bad('Блиц уже закончился.');
    let run = runOf(u.id, set, prac);
    if (!run) throw bad('Сначала нажми «Начать».');
    if (run.finished_at) return { ...view(u.id, prac, set.id), late: true };
    if (U.now() > deadline(run, set) + GRACE_MS) { finish(run, set, prac); return { ...view(u.id, prac, set.id), late: true }; }
    const plan = JSON.parse(run.plan);
    const item = plan[run.pos];
    // Ответ на уже пройденный вопрос (двойное нажатие) — просто текущее состояние
    if (Number(body.n) !== run.pos + 1) return view(u.id, prac, set.id);
    const pick = Number(body.pick);
    if (!Number.isInteger(pick) || pick < 0 || pick >= item.perm.length) throw bad('Выбери вариант.');
    const correct = item.perm[pick] === 0; // правильный ответ в наборе всегда записан первым
    const right = item.perm.indexOf(0);
    q('UPDATE blitz_runs SET pos = pos + 1, score = score + ? WHERE user_id = ? AND set_id = ?').run(correct ? 1 : 0, u.id, keyOf(set, prac));
    run = runOf(u.id, set, prac);
    if (run.pos >= plan.length) finish(run, set, prac);
    return { ...view(u.id, prac, set.id), result: { correct, right } };
  });

  // Итог в пятницу, 17:00–19:00: один раз на набор, только тем, у кого включены пуши
  db.exec('CREATE TABLE IF NOT EXISTS blitz_summary (set_id TEXT PRIMARY KEY, at INTEGER NOT NULL)');
  function summaryTick() {
    const m = U.msk(), set = activeSet();
    if (!set || !notify || m.hour < 17 || m.hour >= 19 || summaryDay(set) !== m.day) return;
    if (!q('INSERT OR IGNORE INTO blitz_summary (set_id, at) VALUES (?, ?)').run(set.id, U.now()).changes) return;
    for (const r of q('SELECT DISTINCT s.user_id AS id FROM push_subs s JOIN users u ON u.id = s.user_id WHERE u.nick IS NOT NULL').all()) {
      fireAndForget(notify([r.id], { title: `Блиц «${set.title}»`, body: summaryText(set, leaderboard(set, r.id), m.day), url: '/#games', tag: 'blitz-sum' }));
    }
  }
  if (notify) setInterval(() => { try { summaryTick(); } catch (e) { console.error('[blitz]', e.message); } }, 5 * 60e3).unref();

  return { activeSet };
}

module.exports = { register, SETS, summaryDay, summaryText };
