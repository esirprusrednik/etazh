// Рабочие субботы: какой день плана недели к ним применять
const WORK_SAT = { '2027-02-20': 'Пн' };

// Сокращённые на час предпраздничные дни
const SHORT = new Set(['2026-04-30', '2026-05-08', '2026-06-11', '2026-11-03', '2027-02-20', '2027-04-30', '2027-06-11', '2027-11-03']);

const WD = [null, 'Пн', 'Вт', 'Ср', 'Чт', 'Пт', null];
const dow = (day) => new Date(day + 'T00:00:00Z').getUTCDay();

// День плана недели, если день рабочий; null — выходной или праздник
function workdayName(day) {
  if (WORK_SAT[day]) return WORK_SAT[day];
  if (OFF[day]) return null;
  return WD[dow(day)];
}

const isWeekday = (day) => dow(day) >= 1 && dow(day) <= 5;
const holidayName = (day) => OFF[day] || null;
const isShort = (day) => SHORT.has(day);
const isWorkSaturday = (day) => !!WORK_SAT[day];
const covered = (day) => day.slice(0, 4) <= '2027';

